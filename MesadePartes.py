import csv
import os
from datetime import datetime

try:
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch
except ImportError:
    plt = None
    Patch = None

ARCHIVO_CSV = "solicitudes.csv"
ARCHIVO_EXCEL = "solicitudes.xlsx"
ARCHIVO_RECHAZADAS = "solicitudes_rechazadas.log"

MAX_BARRAS_PRIORIDAD = 10

CAMPOS = [
    "Codigo",
    "Solicitante",
    "Ubicacion",
    "Recurso",
    "Cantidad",
    "Unidad",
    "Damnificados",
    "Emergencia",
    "Puntaje"
]

CAMPOS_NUMERICOS = ["Cantidad", "Damnificados", "Puntaje"]

RECURSOS = [
    "Agua",
    "Alimentos",
    "Medicamentos",
    "Frazadas",
    "Otros"
]

NIVELES_EMERGENCIA = ["Baja", "Media", "Alta"]

PUNTAJES_EMERGENCIA = {
    "Baja": 1,
    "Media": 2,
    "Alta": 3
}


def preparar_archivo():
    """Crea el CSV con encabezados si todavía no existe."""
    if not os.path.exists(ARCHIVO_CSV):
        with open(ARCHIVO_CSV, "w", newline="", encoding="utf-8") as archivo:
            escritor = csv.DictWriter(archivo, fieldnames=CAMPOS)
            escritor.writeheader()


def validar_fila(fila):
    """Devuelve None si la fila es válida; si no, el motivo del rechazo."""
    for campo in CAMPOS:
        if not (fila.get(campo) or "").strip():
            return f"campo vacío o ausente: {campo}"

    for campo in CAMPOS_NUMERICOS:
        try:
            if int(fila[campo]) <= 0:
                return f"{campo} debe ser mayor que cero"
        except ValueError:
            return f"{campo} no es un número entero"

    if fila["Emergencia"] not in PUNTAJES_EMERGENCIA:
        return f"nivel de emergencia desconocido: {fila['Emergencia']}"

    return None


def registrar_rechazada(numero_linea, fila, motivo):
    """Guarda en un log la fila inválida para no perder trazabilidad."""
    with open(ARCHIVO_RECHAZADAS, "a", encoding="utf-8") as log:
        marca = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        log.write(f"{marca} | fila {numero_linea} | {motivo} | {dict(fila)}\n")


def cargar_solicitudes():
    """Carga las solicitudes válidas y registra las filas dañadas."""
    preparar_archivo()

    validas = []
    rechazadas = 0

    with open(ARCHIVO_CSV, "r", newline="", encoding="utf-8") as archivo:
        lector = csv.DictReader(archivo)

        # La fila 1 es el encabezado, los datos empiezan en la 2.
        for numero_linea, fila in enumerate(lector, start=2):
            motivo = validar_fila(fila)

            if motivo is None:
                validas.append(fila)
            else:
                rechazadas += 1
                registrar_rechazada(numero_linea, fila, motivo)

    if rechazadas:
        print(
            f"⚠️ ALERTA: se omitieron {rechazadas} fila(s) inválida(s). "
            f"Revisa el detalle en '{ARCHIVO_RECHAZADAS}'."
        )

    return validas


def guardar_solicitudes(solicitudes):
    """Guarda todas las solicitudes en el archivo CSV."""
    with open(ARCHIVO_CSV, "w", newline="", encoding="utf-8") as archivo:
        escritor = csv.DictWriter(archivo, fieldnames=CAMPOS)
        escritor.writeheader()
        escritor.writerows(solicitudes)


def pedir_texto(mensaje):
    """Pide un texto y vuelve a solicitarlo si está vacío."""
    while True:
        respuesta = input(mensaje).strip()

        if respuesta:
            return respuesta

        print("⚠️ ALERTA: la respuesta no puede estar vacía. Intenta nuevamente.")


def pedir_numero_positivo(mensaje):
    """Pide un número entero mayor que cero."""
    while True:
        respuesta = input(mensaje).strip()

        try:
            numero = int(respuesta)

            if numero > 0:
                return numero

            print("⚠️ ALERTA: ingresa un número mayor que cero.")

        except ValueError:
            print("⚠️ ALERTA: escribe un número entero válido.")


def pedir_opcion(mensaje, minimo, maximo):
    """Pide una opción dentro del rango permitido."""
    while True:
        respuesta = input(mensaje).strip()

        try:
            opcion = int(respuesta)

            if minimo <= opcion <= maximo:
                return opcion

            print(
                f"⚠️ ALERTA: selecciona un número del "
                f"{minimo} al {maximo}."
            )

        except ValueError:
            print("⚠️ ALERTA: escribe un número válido.")


def crear_codigo(solicitudes):
    """Genera un código consecutivo sin repetir los existentes."""
    mayor_numero = 0

    for solicitud in solicitudes:
        codigo = solicitud.get("Codigo", "")

        if codigo.startswith("SOL-"):
            try:
                numero = int(codigo.split("-")[1])
                if numero > mayor_numero:
                    mayor_numero = numero
            except (ValueError, IndexError):
                pass

    return f"SOL-{mayor_numero + 1:04d}"


def seleccionar_recurso():
    """Muestra los recursos disponibles y devuelve el elegido."""
    print("\nTipos de recurso:")

    for numero, recurso in enumerate(RECURSOS, start=1):
        print(f"{numero}. {recurso}")

    opcion = pedir_opcion(
        "Selecciona el tipo de recurso: ",
        1,
        len(RECURSOS)
    )

    return RECURSOS[opcion - 1]


def seleccionar_emergencia():
    """Muestra los niveles de emergencia y devuelve el elegido."""
    print("\nNivel de emergencia:")

    for numero, nivel in enumerate(NIVELES_EMERGENCIA, start=1):
        print(f"{numero}. {nivel}")

    opcion = pedir_opcion(
        "Selecciona el nivel de emergencia: ",
        1,
        len(NIVELES_EMERGENCIA)
    )

    return NIVELES_EMERGENCIA[opcion - 1]


def registrar_solicitud(solicitudes):
    """Solicita los datos y registra una nueva solicitud."""
    print("\n--- Registrar solicitud de ayuda ---")

    solicitante = pedir_texto("Nombre del solicitante: ")
    ubicacion = pedir_texto("Ubicación o comunidad afectada: ")
    recurso = seleccionar_recurso()
    cantidad = pedir_numero_positivo("Cantidad solicitada: ")
    unidad = pedir_texto("Unidad (litros, cajas, unidades, etc.): ")
    damnificados = pedir_numero_positivo(
        "Número de personas damnificadas: "
    )
    emergencia = seleccionar_emergencia()

    # El puntaje aumenta según la cantidad de damnificados
    # y el nivel de emergencia.
    puntaje = damnificados * PUNTAJES_EMERGENCIA[emergencia]

    solicitud = {
        "Codigo": crear_codigo(solicitudes),
        "Solicitante": solicitante,
        "Ubicacion": ubicacion,
        "Recurso": recurso,
        "Cantidad": cantidad,
        "Unidad": unidad,
        "Damnificados": damnificados,
        "Emergencia": emergencia,
        "Puntaje": puntaje
    }

    solicitudes.append(solicitud)
    guardar_solicitudes(solicitudes)

    print("\nSolicitud registrada correctamente.")
    print(f"Código asignado: {solicitud['Codigo']}")
    print(f"Puntaje de prioridad: {puntaje}")


def mostrar_detalle(solicitud):
    """Imprime los datos de una solicitud."""
    print("----------------------------------------")
    print(f"Código: {solicitud['Codigo']}")
    print(f"Solicitante: {solicitud['Solicitante']}")
    print(f"Ubicación: {solicitud['Ubicacion']}")
    print(
        f"Recurso: {solicitud['Recurso']} "
        f"({solicitud['Cantidad']} {solicitud['Unidad']})"
    )
    print(f"Personas damnificadas: {solicitud['Damnificados']}")
    print(f"Nivel de emergencia: {solicitud['Emergencia']}")
    print(f"Puntaje de prioridad: {solicitud['Puntaje']}")


def mostrar_solicitudes(solicitudes):
    """Muestra las solicitudes ordenadas por puntaje."""
    if not solicitudes:
        print("\nTodavía no hay solicitudes registradas.")
        return

    ordenadas = sorted(
        solicitudes,
        key=lambda solicitud: (
            int(solicitud["Puntaje"]),
            int(solicitud["Damnificados"])
        ),
        reverse=True
    )

    print("\n--- Solicitudes ordenadas por prioridad ---")

    for solicitud in ordenadas:
        mostrar_detalle(solicitud)


def buscar_solicitud(solicitudes):
    """Busca una solicitud usando su código."""
    if not solicitudes:
        print("\nNo hay solicitudes para buscar.")
        return

    while True:
        codigo = input(
            "\nEscribe el código de la solicitud "
            "(o 0 para volver al menú): "
        ).strip().upper()

        if codigo == "0":
            return

        if not codigo:
            print("⚠️ ALERTA: el código no puede estar vacío.")
            continue

        for solicitud in solicitudes:
            if solicitud["Codigo"].upper() == codigo:
                print("\nSolicitud encontrada:")
                mostrar_detalle(solicitud)
                return

        print("⚠️ ALERTA: no se encontró ese código. Intenta nuevamente.")


