def descargar_csv(solicitudes):
    """Guarda y descarga el archivo CSV."""
    guardar_solicitudes(solicitudes)
    descargar_archivo(ARCHIVO_CSV)


def crear_excel(solicitudes):
    """Crea un archivo Excel con las solicitudes."""
    try:
        from openpyxl import Workbook
        from openpyxl.styles import Font, PatternFill
    except ImportError:
        print("⚠️ ALERTA: no se encontró la librería openpyxl.")
        print("En una celda de Colab, ejecuta: !pip install openpyxl")
        return False

    libro = Workbook()
    hoja = libro.active
    hoja.title = "Solicitudes"

    # Escribe los encabezados.
    hoja.append(CAMPOS)

    # Da formato a los encabezados.
    for celda in hoja[1]:
        celda.font = Font(bold=True, color="FFFFFF")
        celda.fill = PatternFill(
            fill_type="solid",
            fgColor="1F4E78"
        )

    # Escribe cada solicitud; los campos numéricos se guardan como
    # números para poder sumar, filtrar u ordenar en Excel.
    for solicitud in solicitudes:
        fila = []

        for campo in CAMPOS:
            valor = solicitud.get(campo, "")

            if campo in CAMPOS_NUMERICOS:
                valor = int(valor)

            fila.append(valor)

        hoja.append(fila)

    # Ajusta el ancho de las columnas.
    anchos = [15, 25, 25, 18, 15, 18, 18, 18, 18]

    for numero, ancho in enumerate(anchos, start=1):
        letra = hoja.cell(row=1, column=numero).column_letter
        hoja.column_dimensions[letra].width = ancho

    hoja.freeze_panes = "A2"
    libro.save(ARCHIVO_EXCEL)

    return True


def descargar_excel(solicitudes):
    """Crea y descarga el archivo Excel."""
    if crear_excel(solicitudes):
        descargar_archivo(ARCHIVO_EXCEL)


def graficar_prioridades(solicitudes):
    """Muestra gráficos de puntajes, emergencias y damnificados por recurso."""
    if not solicitudes:
        print("⚠️ ALERTA: no hay solicitudes para graficar.")
        return

    if plt is None:
        print("⚠️ ALERTA: no se encontró matplotlib.")
        print("En una celda de Colab, ejecuta: !pip install matplotlib")
        return

    colores_emergencia = {
        "Baja": "seagreen",
        "Media": "orange",
        "Alta": "firebrick"
    }

    ordenadas = sorted(
        solicitudes,
        key=lambda solicitud: int(solicitud["Puntaje"]),
        reverse=True
    )

    # Solo se grafican las de mayor prioridad para que las barras
    # sigan siendo legibles.
    principales = ordenadas[:MAX_BARRAS_PRIORIDAD]

    codigos = [s["Codigo"] for s in principales]
    puntajes = [int(s["Puntaje"]) for s in principales]
    colores = [
        colores_emergencia.get(s["Emergencia"], "gray") for s in principales
    ]

    cantidades = [
        sum(1 for s in solicitudes if s["Emergencia"] == nivel)
        for nivel in NIVELES_EMERGENCIA
    ]

    damnificados_por_recurso = [
        sum(int(s["Damnificados"]) for s in solicitudes
            if s["Recurso"] == recurso)
        for recurso in RECURSOS
    ]

    figura, ejes = plt.subplots(1, 3, figsize=(18, 5))

    # Gráfico 1: puntaje de prioridad de las solicitudes principales.
    barras = ejes[0].bar(codigos, puntajes, color=colores)

    if len(ordenadas) > MAX_BARRAS_PRIORIDAD:
        titulo = f"Top {MAX_BARRAS_PRIORIDAD} solicitudes por prioridad"
    else:
        titulo = "Puntaje de prioridad por solicitud"

    ejes[0].set_title(titulo)
    ejes[0].set_xlabel("Código de solicitud")
    ejes[0].set_ylabel("Puntaje")
    ejes[0].tick_params(axis="x", rotation=45)
    ejes[0].grid(axis="y", linestyle="--", alpha=0.4)

    for barra, puntaje in zip(barras, puntajes):
        ejes[0].text(
            barra.get_x() + barra.get_width() / 2,
            barra.get_height(),
            str(puntaje),
            ha="center",
            va="bottom"
        )

    leyenda = [
        Patch(
            color=colores_emergencia[nivel],
            label=f"Emergencia {nivel.lower()}"
        )
        for nivel in NIVELES_EMERGENCIA
    ]
    ejes[0].legend(handles=leyenda)

    # Gráfico 2: cantidad de solicitudes por nivel de emergencia.
    if sum(cantidades) > 0:
        ejes[1].pie(
            cantidades,
            labels=NIVELES_EMERGENCIA,
            colors=[colores_emergencia[n] for n in NIVELES_EMERGENCIA],
            autopct="%1.1f%%",
            startangle=90
        )
    ejes[1].set_title("Solicitudes por nivel de emergencia")

    # Gráfico 3: damnificados según el recurso solicitado.
    barras_recurso = ejes[2].bar(
        RECURSOS, damnificados_por_recurso, color="steelblue"
    )
    ejes[2].set_title("Damnificados por tipo de recurso")
    ejes[2].set_xlabel("Recurso")
    ejes[2].set_ylabel("Personas damnificadas")
    ejes[2].tick_params(axis="x", rotation=30)
    ejes[2].grid(axis="y", linestyle="--", alpha=0.4)

    for barra, valor in zip(barras_recurso, damnificados_por_recurso):
        ejes[2].text(
            barra.get_x() + barra.get_width() / 2,
            barra.get_height(),
            str(valor),
            ha="center",
            va="bottom"
        )

    figura.tight_layout()
    plt.show()


def mostrar_menu():
    """Muestra las opciones principales del sistema."""
    print("\n====== MESA DE PARTES DIGITAL ======")
    print("1. Registrar solicitud")
    print("2. Mostrar solicitudes por prioridad")
    print("3. Buscar solicitud por código")
    print("4. Descargar archivo CSV")
    print("5. Descargar archivo Excel")
    print("6. Mostrar gráficos de prioridades")
    print("7. Salir")


def iniciar_programa():
    """Ejecuta el menú principal."""
    solicitudes = cargar_solicitudes()

    while True:
        mostrar_menu()
        opcion = pedir_opcion("Elige una opción: ", 1, 7)

        if opcion == 1:
            registrar_solicitud(solicitudes)
        elif opcion == 2:
            mostrar_solicitudes(solicitudes)
        elif opcion == 3:
            buscar_solicitud(solicitudes)
        elif opcion == 4:
            descargar_csv(solicitudes)
        elif opcion == 5:
            descargar_excel(solicitudes)
        elif opcion == 6:
            graficar_prioridades(solicitudes)
        elif opcion == 7:
            print("Programa finalizado.")
            break


if __name__ == "__main__":
    iniciar_programa()
